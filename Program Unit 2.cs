Console.WriteLine("Hello, World"); // Regular print;
Console.WriteLine("Hello", "World"); // Print separate elements. The "," adds a space between elements by default.
Console.WriteLine("Hello\nWorld"); // The \n adds a new line 
Console.WriteLine("Hello\tWorld"); // The \t adds a tab space
Console.WriteLine("She said, \"Hi!\""); // The \" allows to write the " inside the string.